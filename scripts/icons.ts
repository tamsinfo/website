// Extracts the Solar Duotone Bold icons the site uses from @iconify-json/solar
// into a small typed module, so the bundle never ships the whole collection.
// Run with: bun scripts/icons.ts
import { writeFileSync } from "node:fs";
import solar from "@iconify-json/solar/icons.json" with { type: "json" };

const names = [
  "arrow-right", "arrow-right-up", "arrow-left", "alt-arrow-down", "alt-arrow-right", "close-circle",
  "hamburger-menu", "volume-loud", "volume-cross", "music-note-2", "headphones-round-sound",
  "cloud-check", "users-group-rounded", "code-square", "key", "cloud-storage", "graph-new-up",
  "widget-add", "magic-stick-3", "buildings-2", "chart-2", "transfer-horizontal", "checklist",
  "delivery", "file-check", "inbox-in", "container", "routing-3", "cpu-bolt", "pulse-2", "car",
  "ladle", "reel", "pills", "ruler-cross-pen", "washing-machine", "phone", "letter", "map-point",
  "check-circle", "danger-circle", "refresh", "link", "unlink", "weigher", "qr-code",
  "shield-check", "history", "layers", "global", "documents", "server-square-update",
  "user-id", "settings", "eye", "lock-keyhole", "database", "danger-triangle", "plug-circle",
];

type Icon = { body: string; width?: number; height?: number };
const icons = solar.icons as Record<string, Icon>;
const out: Record<string, string> = {};
for (const name of names) {
  const icon = icons[`${name}-bold-duotone`];
  if (!icon) throw new Error(`missing icon: ${name}-bold-duotone`);
  out[name] = icon.body;
}

const source = `// Generated by scripts/icons.ts from @iconify-json/solar (Solar by 480 Design, CC BY 4.0).
// Do not edit by hand; add the name to the script and re-run it.
export const solar = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof solar;
`;
writeFileSync(new URL("../src/lib/icons/solar.ts", import.meta.url), source);
console.log(`wrote ${names.length} icons`);
