// Extracts only the Solar Duotone Bold icons the site uses into a small TS module,
// so no icon is fetched from the Iconify API at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { getIconData, iconToSVG } from "@iconify/utils";

const set = JSON.parse(
  readFileSync(new URL("../node_modules/@iconify-json/solar/icons.json", import.meta.url), "utf8"),
);

export const ICONS = [
  "arrow-right", "arrow-right-up", "alt-arrow-down", "alt-arrow-right", "hamburger-menu", "close-circle",
  "phone", "letter", "map-point", "calendar", "check-circle", "danger-triangle", "restart",
  "running-2", "link-broken", "eye", "shield-keyhole", "maximize-square",
  "cloud-upload", "headphones-round", "code-square", "key",
  "magnifer", "map", "ruler-pen", "rocket", "checklist", "server", "refresh-circle",
  "cloud-storage", "graph-up", "widget", "cpu-bolt", "chart-2", "routing", "settings", "layers",
  "users-group-rounded", "case", "lightbulb", "shield-check", "pulse", "database", "document-text",
  "info-circle", "home-2", "global", "history", "transfer-horizontal", "hand-shake", "lock-keyhole",
  "play-circle", "pause-circle", "palette", "box", "structure", "target", "bolt",
  "delivery", "globus", "pen-2", "documents", "users-group-two-rounded", "widget-5", "test-tube",
  "wheel", "fridge", "settings-minimalistic", "cloud-check", "diagram-up", "layers-minimalistic",
  "programming", "buildings-3", "link-circle", "clock-circle", "cart-large-2", "calendar-mark",
  "letter-opened", "plug-circle", "scanner", "sledgehammer", "fire", "chat-round-dots", "alt-arrow-left",
];

const out = {};
for (const name of ICONS) {
  const data = getIconData(set, `${name}-bold-duotone`);
  if (!data) throw new Error(`Missing Solar icon: ${name}-bold-duotone`);
  const svg = iconToSVG(data, { height: "auto" });
  out[name] = { body: svg.body, viewBox: svg.attributes.viewBox };
}

const file = `// Generated by scripts/build-icons.mjs — Solar Duotone Bold (CC BY 4.0, 480 Design) via Iconify.
// Do not edit by hand; run \`npm run icons\`.
export const solarIcons = ${JSON.stringify(out, null, 0)} as const;
export type IconName = keyof typeof solarIcons;
`;
writeFileSync(new URL("../src/icons/solar.ts", import.meta.url), file);
console.log(`Wrote ${Object.keys(out).length} icons`);
